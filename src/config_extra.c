#include "config.h"
#include "util.h"
#include <stdio.h>
#include <string.h>
#include <wchar.h>
#include <windows.h>

bool config_save(const config_t* c, const char* path) {
    if (!c || !path || !path[0]) return false;

    // 确保目录存在
    char dir[MAX_PATH] = "";
    strncpy(dir, path, sizeof(dir)-1);
    char* bs = strrchr(dir, '\\');
    if (bs) {
        *bs = '\0';
        // 递归创建（简单版：只建一层，ProgramData\LANTimeSync 已由安装创建）
        CreateDirectoryA(dir, NULL);
    }

    // 写到临时文件再原子替换
    char tmp[MAX_PATH+16] = "";
    _snprintf(tmp, sizeof(tmp), "%s.tmp", path);

    FILE* f = fopen(tmp, "w");
    if (!f) return false;

    const char* levelStr = "info";
    if (c->log_level == LOG_LEVEL_DEBUG) levelStr = "debug";
    else if (c->log_level == LOG_LEVEL_WARN) levelStr = "warn";
    else if (c->log_level == LOG_LEVEL_ERROR) levelStr = "error";

    fprintf(f, "; LAN Time Sync configuration\n");
    fprintf(f, "; generated by GUI - %s\n", path);
    fprintf(f, "\n[server]\n");
    fprintf(f, "address = \"%s\"\n", c->server);
    fprintf(f, "port = %d\n", c->port);
    fprintf(f, "\n[sync]\n");
    fprintf(f, "interval_minutes = %d\n", c->interval_minutes);
    fprintf(f, "retry_seconds = %d\n", c->retry_seconds);
    fprintf(f, "timeout_ms = %d\n", c->timeout_ms);
    fprintf(f, "max_offset_ms = %d\n", c->max_offset_ms);
    fprintf(f, "min_offset_ms = %d\n", c->min_offset_ms);
    fprintf(f, "force_enabled = %s\n", c->force_enabled ? "true" : "false");
    fprintf(f, "force_flag = %s\n", c->force_flag ? "true" : "false");
    fprintf(f, "sync_on_start = %s\n", c->sync_on_start ? "true" : "false");
    fprintf(f, "allow_large_offset = %s\n", c->allow_large_offset ? "true" : "false");
    fprintf(f, "\n[service]\n");
    fprintf(f, "enabled = %s\n", c->service_enabled ? "true" : "false");
    fprintf(f, "\n[log]\n");
    fprintf(f, "file_enabled = %s\n", c->log_enabled ? "true" : "false");
    fprintf(f, "file_path = \"%s\"\n", c->log_file);
    fprintf(f, "level = \"%s\"\n", levelStr);
    fclose(f);

    // 原子替换
    // 先尝试 MoveFileEx 覆盖
    if (MoveFileExA(tmp, path, MOVEFILE_REPLACE_EXISTING)) return true;
    // 回退：删除原文件再移动
    DeleteFileA(path);
    if (MoveFileA(tmp, path)) return true;
    // 最后尝试直接重命名
    remove(path);
    if (rename(tmp, path)==0) return true;
    return false;
}

/* wide-path variant of config_save (no ACP/UTF-8 conversion loss).
   Used for %TEMP% files whose path may contain non-ASCII (user name).
   Content bytes are identical to config_save (already UTF-8). */
bool config_save_w(const config_t* c, const WCHAR* wpath) {
    if (!c || !wpath || !wpath[0]) return false;

    WCHAR dir[MAX_PATH] = L"";
    wcsncpy(dir, wpath, MAX_PATH - 1);
    dir[MAX_PATH - 1] = L'\0';
    WCHAR* bs = wcsrchr(dir, L'\\');
    if (bs) {
        *bs = L'\0';
        CreateDirectoryW(dir, NULL);
    }

    WCHAR tmp[MAX_PATH + 16] = L"";
    _snwprintf(tmp, MAX_PATH + 15, L"%s.tmp", wpath);
    tmp[MAX_PATH + 15] = L'\0';

    FILE* f = NULL;
    _wfopen_s(&f, tmp, L"w"); /* byte mode: no BOM, UTF-8 bytes pass through */
    if (!f) return false;

    const char* levelStr = "info";
    if (c->log_level == LOG_LEVEL_DEBUG) levelStr = "debug";
    else if (c->log_level == LOG_LEVEL_WARN) levelStr = "warn";
    else if (c->log_level == LOG_LEVEL_ERROR) levelStr = "error";

    fprintf(f, "; LAN Time Sync configuration\n");
    fprintf(f, "; generated by GUI (temp file)\n");
    fprintf(f, "\n[server]\n");
    fprintf(f, "address = \"%s\"\n", c->server);
    fprintf(f, "port = %d\n", c->port);
    fprintf(f, "\n[sync]\n");
    fprintf(f, "interval_minutes = %d\n", c->interval_minutes);
    fprintf(f, "retry_seconds = %d\n", c->retry_seconds);
    fprintf(f, "timeout_ms = %d\n", c->timeout_ms);
    fprintf(f, "max_offset_ms = %d\n", c->max_offset_ms);
    fprintf(f, "min_offset_ms = %d\n", c->min_offset_ms);
    fprintf(f, "force_enabled = %s\n", c->force_enabled ? "true" : "false");
    fprintf(f, "force_flag = %s\n", c->force_flag ? "true" : "false");
    fprintf(f, "sync_on_start = %s\n", c->sync_on_start ? "true" : "false");
    fprintf(f, "allow_large_offset = %s\n", c->allow_large_offset ? "true" : "false");
    fprintf(f, "\n[service]\n");
    fprintf(f, "enabled = %s\n", c->service_enabled ? "true" : "false");
    fprintf(f, "\n[log]\n");
    fprintf(f, "file_enabled = %s\n", c->log_enabled ? "true" : "false");
    fprintf(f, "file_path = \"%s\"\n", c->log_file);
    fprintf(f, "level = \"%s\"\n", levelStr);
    fclose(f);

    if (MoveFileExW(tmp, wpath, MOVEFILE_REPLACE_EXISTING)) return true;
    DeleteFileW(wpath);
    if (MoveFileW(tmp, wpath)) return true;
    return false;
}
